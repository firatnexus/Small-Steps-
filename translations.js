  const SUPPORTED_LANGS = Object.keys(TRANSLATIONS);
  const DEFAULT_LANG = "en";
  const LANG_KEY = "small-steps-language";

  let currentLang = DEFAULT_LANG;
  const changeCallbacks = [];

  function t(key, params) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS[DEFAULT_LANG];
    let str = dict[key];
    if (typeof str !== "string") str = TRANSLATIONS[DEFAULT_LANG][key] ?? key;
    if (params) {
      str = str.replace(/\{(\w+)\}/g, (_, k) =>
        Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : `{${k}}`);
    }
    return str;
  }

  function detectInitialLang() {
    let stored = null;
    try { stored = localStorage.getItem(LANG_KEY); } catch {}
    if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
    const nav = (navigator.language || "").slice(0, 2).toLowerCase();
    if (SUPPORTED_LANGS.includes(nav)) return nav;
    return DEFAULT_LANG;
  }

  function applyLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;
    currentLang = lang;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(el => {
      el.setAttribute("aria-label", t(el.dataset.i18nAria));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      el.setAttribute("title", t(el.dataset.i18nTitle));
    });

    const input = document.querySelector("#task-input");
    if (input) input.setAttribute("placeholder", t("placeholder"));

    const langSelect = document.querySelector("#lang-select");
    if (langSelect && langSelect.value !== lang) langSelect.value = lang;

    changeCallbacks.forEach(fn => { try { fn(lang); } catch (e) { console.error(e); } });
  }

  function setLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) return;
    try { localStorage.setItem(LANG_KEY, lang); } catch {}
    applyLanguage(lang);
  }

  function onLanguageChange(fn) {
    if (typeof fn === "function") changeCallbacks.push(fn);
  }

  function buildLangSelect(selectEl) {
    if (!selectEl) return;
    selectEl.replaceChildren(...Object.entries(TRANSLATIONS).map(([code, dict]) => {
      const opt = document.createElement("option");
      opt.value = code;
      opt.textContent = dict.name;
      return opt;
    }));
    selectEl.value = currentLang;
  }

  window.i18n = {
    TRANSLATIONS, SUPPORTED_LANGS, DEFAULT_LANG,
    t, getLang: () => currentLang,
    detectInitialLang, applyLanguage, setLanguage,
    onLanguageChange, buildLangSelect
  };
